/**
 * @file
 * @brief Inverts the screened Coulomb potential to obtain a distance from a potential.
 * @author Jan Drewniok (Drewniok)
 * @author Marcel Walter (marcelwa)
 */

#pragma once

#include "fiction/technology/sidb/model/physical_constants.hpp"
#include "fiction/technology/sidb/model/simulation_parameters.hpp"

#include <algorithm>
#include <cmath>
#include <cstdint>
#include <limits>
#include <numeric>
#include <stdexcept>

namespace fiction::sidb::model
{

/**
 * The electrostatic potential on hydrogen-passivated silicon is typically modeled using a screened Coulomb potential.
 * This electrostatic potential is commonly employed to determine the electrostatic potential for a given distance
 * (between SiDB and point under consideration) and given physical parameters. However, the function provided here
 * serves the inverse purpose by calculating the distance for a given potential and given physical parameters.
 * The potential is the magnitude generated by a single elementary charge.
 *
 * The distance rounds upward to the requested decimal precision, with a minimum of `10^-precision` nm.
 * Floating-point evaluation error can exceed the requested decimal precision, especially for extreme physical
 * parameters. Zero potential returns positive infinity. Positive infinite potential returns the minimum distance.
 *
 * @param params The physical parameters for a given hydrogen-passivated silicon surface.
 * @param potential The electrostatic potential (unit: V) to be converted to a distance.
 * @param precision Number of decimal places, at most `std::numeric_limits<double>::digits10`.
 * @return The distance (unit: nm), or positive infinity if no finite `double` distance can represent the inverse.
 * @throws std::invalid_argument If potential is negative or NaN, the relative permittivity or screening distance is
 * non-positive or non-finite, or precision exceeds the decimal precision of `double`.
 */
[[nodiscard]] inline double potential_to_distance_conversion(
    const double potential, const sidb::model::simulation_parameters& params = sidb::model::simulation_parameters{},
    const uint64_t precision = 2)
{
    if (std::isnan(potential) || potential < 0 || !std::isfinite(params.epsilon_r) || params.epsilon_r <= 0 ||
        !std::isfinite(params.lambda_tf) || params.lambda_tf <= 0 || precision > std::numeric_limits<double>::digits10)
    {
        throw std::invalid_argument{
            "potential-to-distance conversion requires a non-negative potential, positive finite "
            "physical parameters, and precision within double's decimal precision"};
    }

    if (potential == 0)
    {
        return std::numeric_limits<double>::infinity();
    }

    const auto scale     = std::pow(10.0, static_cast<double>(precision));
    const auto step_size = 1.0 / scale;
    if (std::isinf(potential))
    {
        return step_size;
    }

    // Logarithms keep finite positive inputs usable when the screened potential would underflow or overflow.
    const auto coefficient = params.k() * model::ELEMENTARY_CHARGE;
    const auto log_coefficient =
        std::log(model::K_E) + std::log(model::ELEMENTARY_CHARGE) + std::log(1e9) - std::log(params.epsilon_r);
    const auto log_potential = std::log(potential);
    /**
     * @brief Tests whether the screened potential exceeds the requested potential.
     * @param distance Distance in nm.
     * @return Whether the distance lies below the inverse.
     */
    const auto below_inverse = [&](const double distance) noexcept
    {
        const auto screening          = std::exp(-distance / params.lambda_tf);
        const auto screened_potential = coefficient / (distance * 1e-9) * screening;
        if (std::isnormal(coefficient) && std::isnormal(screening) && std::isnormal(screened_potential))
        {
            return screened_potential > potential;
        }
        return log_coefficient - std::log(distance) - (distance / params.lambda_tf) > log_potential;
    };

    if (!below_inverse(step_size))
    {
        return step_size;
    }

    double lower = step_size;
    double upper = 1.0;
    while (below_inverse(upper))
    {
        lower = upper;
        if (upper == std::numeric_limits<double>::max())
        {
            return std::numeric_limits<double>::infinity();
        }
        upper = upper > std::numeric_limits<double>::max() / 2 ? std::numeric_limits<double>::max() : upper * 2;
    }

    while (true)
    {
        const auto middle = std::midpoint(lower, upper);
        if (middle <= lower || middle >= upper)
        {
            break;
        }
        if (below_inverse(middle))
        {
            lower = middle;
        }
        else
        {
            upper = middle;
        }
    }

    // Decimal rounding has no effect once the requested step is smaller than the spacing between doubles.
    const auto scaled_distance = upper * scale;
    if (!std::isfinite(scaled_distance))
    {
        return upper;
    }
    const auto rounded_down = std::floor(scaled_distance) / scale;
    return !below_inverse(rounded_down) ? rounded_down : std::max(upper, std::ceil(scaled_distance) / scale);
}

}  // namespace fiction::sidb::model
